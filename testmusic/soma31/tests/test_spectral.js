'use strict';
const assert=require('node:assert/strict'),sp=require('../spectral_lab.js');
assert(Math.abs(sp.weightedA(1000))<.1,'A weighting reference must be 0 dB at 1 kHz');
assert(sp.weightedA(100)<-15,'bass should be downweighted in illustrative curve');
assert(sp.weightedA(5000)>sp.weightedA(100),'shape plausibility');
const fs=48000,n=8192,step=fs/(2*n),freq=sp.frequencies(80,90,9000);
const tone=(hz,base=-95)=>Float32Array.from({length:n},(_,i)=>base+50*Math.exp(-(((i*step-hz)/18)**2)));
const data=tone(196);
const bands=sp.logBands(data,fs,freq),pk=bands.indexOf(Math.max(...bands));
assert(Math.abs(Math.log2(freq[pk]/196))*1200<120,'tone peak should sit near 196 Hz');
let f=new sp.RoomField(50),r;
for(let i=0;i<320;i++)r=f.feed(data,fs,.08,i*.11);
assert(r.converged,`stationary environment must converge, got ${JSON.stringify({age:r.age,diff:r.diff,stability:r.stability})}`);
const stable=r.stable.slice();
for(let i=320;i<340;i++)r=f.feed(tone(1550),fs,.08,i*.11);
assert(r.stability<.78,'abrupt changed spectrum must drop stability');
assert(stable.some((v,i)=>Math.abs(v-r.stable[i])>.05),'slow average must evolve');
const unchanged=f.state().age;f.feed(data,fs,0,341*.11);assert.equal(f.state().age,unchanged,'silence must not update spectral fingerprint');
console.log('PASS: spectral log bands, A-weight visualization, convergence, state change, silence gate');
